// Tengasell seed → SQL generator.
// Converts src/data/seed.ts (single source of truth) into a TrailBase
// migration (U1000000003__seed.sql). User references become subselects on
// _user.username so the import is UUID-agnostic.

import { buildSeed } from "../../src/data/seed";

function sqlStr(v: string): string {
  return `'${v.replace(/'/g, "''")}'`;
}

function userExpr(v: string): string {
  if (v.startsWith("seed-user-")) {
    return `(SELECT id FROM _user WHERE username = '${v.slice("seed-user-".length)}')`;
  }
  return sqlStr(v);
}

const seed = buildSeed();

const out: string[] = ["-- Tengasell catalog seed (generated by gen-sql.ts)"];

// categories
out.push("INSERT INTO categories (id, slug, name, name_ja, icon, blurb, sort) VALUES");
out.push(
  seed.categories
    .map(
      (c) =>
        `  (${c.id}, ${sqlStr(c.slug)}, ${sqlStr(c.name)}, ${sqlStr(c.name_ja)}, ${sqlStr(c.icon)}, ${sqlStr(c.blurb)}, ${c.sort})`,
    )
    .join(",\n") + ";",
);

// profiles
out.push(
  "INSERT INTO profiles (id, user, username, display_name, bio, city, rating_avg, rating_count, sales, response_minutes, verified, joined_at) VALUES",
);
out.push(
  seed.profiles
    .map(
      (p) =>
        `  (${p.id}, ${userExpr(p.user)}, ${sqlStr(p.username)}, ${sqlStr(p.display_name)}, ${sqlStr(p.bio)}, ${sqlStr(p.city)}, ${p.rating_avg}, ${p.rating_count}, ${p.sales}, ${p.response_minutes}, ${p.verified}, ${sqlStr(p.joined_at)})`,
    )
    .join(",\n") + ";",
);

// auctions
out.push(
  "INSERT INTO auctions (id, user, seller_username, title, slug, description, category, condition, start_price, current_price, buy_now_price, reserve_price, bid_count, watch_count, views, shipping_fee, shipping, city, ends_at, started_at, status, extension_count, featured, images, created_at, updated_at) VALUES",
);
out.push(
  seed.auctions
    .map(
      (a) =>
        `  (${a.id}, ${userExpr(a.user)}, ${sqlStr(a.seller_username)}, ${sqlStr(a.title)}, ${sqlStr(a.slug)}, ${sqlStr(a.description)}, ${sqlStr(a.category)}, ${sqlStr(a.condition)}, ${a.start_price}, ${a.current_price}, ${a.buy_now_price == null ? "NULL" : a.buy_now_price}, ${a.reserve_price == null ? "NULL" : a.reserve_price}, ${a.bid_count}, ${a.watch_count}, ${a.views}, ${a.shipping_fee}, ${sqlStr(a.shipping)}, ${sqlStr(a.city)}, ${sqlStr(a.ends_at)}, ${sqlStr(a.started_at)}, ${sqlStr(a.status)}, ${a.extension_count}, ${a.featured}, ${sqlStr(a.images)}, ${sqlStr(a.created_at)}, ${sqlStr(a.updated_at)})`,
    )
    .join(",\n") + ";",
);

// bids
out.push(
  "INSERT INTO bids (id, auction_id, user, bidder_username, amount, max_amount, is_auto, status, created_at) VALUES",
);
out.push(
  seed.bids
    .map(
      (b) =>
        `  (${b.id}, ${b.auction_id}, ${userExpr(b.user)}, ${sqlStr(b.bidder_username)}, ${b.amount}, ${b.max_amount}, ${b.is_auto}, ${sqlStr(b.status)}, ${sqlStr(b.created_at)})`,
    )
    .join(",\n") + ";",
);

// watchlist
out.push("INSERT INTO watchlist (id, user, auction_id, created_at) VALUES");
out.push(
  seed.watchlist
    .map((w) => `  (${w.id}, ${userExpr(w.user)}, ${w.auction_id}, ${sqlStr(w.created_at)})`)
    .join(",\n") + ";",
);

// questions
out.push(
  "INSERT INTO questions (id, auction_id, user, asker_username, body, answer, answered_at, created_at) VALUES",
);
out.push(
  seed.questions
    .map(
      (q) =>
        `  (${q.id}, ${q.auction_id}, ${userExpr(q.user)}, ${sqlStr(q.asker_username)}, ${sqlStr(q.body)}, ${q.answer == null ? "NULL" : sqlStr(q.answer)}, ${q.answered_at == null ? "NULL" : sqlStr(q.answered_at)}, ${sqlStr(q.created_at)})`,
    )
    .join(",\n") + ";",
);

// threads
out.push(
  "INSERT INTO threads (id, auction_id, buyer_user, seller_user, buyer_username, seller_username, subject, last_message_at, created_at) VALUES",
);
out.push(
  seed.threads
    .map(
      (t) =>
        `  (${t.id}, ${t.auction_id == null ? "NULL" : t.auction_id}, ${userExpr(t.buyer_user)}, ${userExpr(t.seller_user)}, ${sqlStr(t.buyer_username)}, ${sqlStr(t.seller_username)}, ${sqlStr(t.subject)}, ${t.last_message_at == null ? "NULL" : sqlStr(t.last_message_at)}, ${sqlStr(t.created_at)})`,
    )
    .join(",\n") + ";",
);

// messages
out.push(
  "INSERT INTO messages (id, thread_id, user, sender_username, body, created_at) VALUES",
);
out.push(
  seed.messages
    .map(
      (m) =>
        `  (${m.id}, ${m.thread_id}, ${userExpr(m.user)}, ${sqlStr(m.sender_username)}, ${sqlStr(m.body)}, ${sqlStr(m.created_at)})`,
    )
    .join(",\n") + ";",
);

// orders
out.push(
  "INSERT INTO orders (id, auction_id, auction_title, buyer_user, seller_user, buyer_username, seller_username, final_price, status, pay_by, paid_at, shipped_at, delivered_at, completed_at, carrier, tracking, created_at, updated_at) VALUES",
);
out.push(
  seed.orders
    .map(
      (o) =>
        `  (${o.id}, ${o.auction_id}, ${sqlStr(o.auction_title)}, ${userExpr(o.buyer_user)}, ${userExpr(o.seller_user)}, ${sqlStr(o.buyer_username)}, ${sqlStr(o.seller_username)}, ${o.final_price}, ${sqlStr(o.status)}, ${o.pay_by == null ? "NULL" : sqlStr(o.pay_by)}, ${o.paid_at == null ? "NULL" : sqlStr(o.paid_at)}, ${o.shipped_at == null ? "NULL" : sqlStr(o.shipped_at)}, ${o.delivered_at == null ? "NULL" : sqlStr(o.delivered_at)}, ${o.completed_at == null ? "NULL" : sqlStr(o.completed_at)}, ${o.carrier == null ? "NULL" : sqlStr(o.carrier)}, ${o.tracking == null ? "NULL" : sqlStr(o.tracking)}, ${sqlStr(o.created_at)}, ${sqlStr(o.updated_at)})`,
    )
    .join(",\n") + ";",
);

// payments
out.push(
  "INSERT INTO payments (id, order_id, user, method, amount, status, reference, created_at) VALUES",
);
out.push(
  seed.payments
    .map(
      (p) =>
        `  (${p.id}, ${p.order_id}, ${p.user == null ? "NULL" : userExpr(p.user)}, ${sqlStr(p.method)}, ${p.amount}, ${sqlStr(p.status)}, ${sqlStr(p.reference)}, ${sqlStr(p.created_at)})`,
    )
    .join(",\n") + ";",
);

// ratings
out.push(
  "INSERT INTO ratings (id, order_id, user, ratee_user, ratee_username, direction, score, comment, created_at) VALUES",
);
out.push(
  seed.ratings
    .map(
      (r) =>
        `  (${r.id}, ${r.order_id}, ${userExpr(r.user)}, ${userExpr(r.ratee_user)}, ${sqlStr(r.ratee_username)}, ${sqlStr(r.direction)}, ${r.score}, ${sqlStr(r.comment)}, ${sqlStr(r.created_at)})`,
    )
    .join(",\n") + ";",
);

// notifications
out.push(
  "INSERT INTO notifications (id, user, type, title, body, link, read, created_at) VALUES",
);
out.push(
  seed.notifications
    .map(
      (n) =>
        `  (${n.id}, ${userExpr(n.user)}, ${sqlStr(n.type)}, ${sqlStr(n.title)}, ${sqlStr(n.body)}, ${sqlStr(n.link)}, ${n.read}, ${sqlStr(n.created_at)})`,
    )
    .join(",\n") + ";",
);

const file = "traildepot/migrations/main/U1000000003__seed.sql";
await Bun.write(file, out.join("\n\n") + "\n");
console.log(`Wrote ${file}: ${seed.auctions.length} auctions, ${seed.bids.length} bids, ${seed.profiles.length} profiles.`);
